package com.storyzip.payment.domain;

/**
 * 환불 처리 분류 — 응답 DTO 및 로그/감사 추적용.
 *
 * <p>환불 정책 제4조에 명시된 케이스를 직접 대응한다.
 */
public enum RefundType {

    /** 7일 이내 미사용 — 결제 금액 전액 현금 환불 (구독·종량제 공통). */
    FULL,

    /**
     * 종량제 — 7일 이내 일부 사용. 미사용 크레딧 비율로 부분 현금 환불.
     * (현재 정책에서는 단순 변심 시 일부 사용 환불 차단 — 회사 귀책만 허용. 향후 정책 완화 시 사용.)
     */
    PARTIAL_USED,

    /** 구독 — 7일 이내 일부 이용. 잔여 일수 비례 부분 현금 환불. (정책상 현재 차단, 향후 사용.) */
    PARTIAL_DAYS,

    /** 회사 귀책 — 구독 전액 현금 환불. */
    COMPANY_FAULT,

    /**
     * 회사 귀책 — 종량제 전액 크레딧 보상 (약관 제4조 1항 회사 귀책 분기).
     * 현금 환불 없이 결제 시 받은 크레딧을 다시 지급한다. PortOne cancel 호출 안 함.
     */
    COMPANY_FAULT_CREDIT
}
